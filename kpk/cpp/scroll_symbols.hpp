static const int FONT_SYMBOLS_COUNT =
    (int)(sizeof(FONT_SYMBOLS) / sizeof(FONT_SYMBOLS[0]));

/* Returns pointer to 5x3 bitmap for symbol c, or nullptr */
static const uint8_t (*get_symbol(char c))[3] {
    for (int i = 0; i < FONT_SYMBOLS_COUNT; i++)
        if (FONT_SYMBOLS[i].ch == c)
            return FONT_SYMBOLS[i].bitmap;
    return nullptr;
}
