/* Returns pointer to 5x3 bitmap for character c, or nullptr if not found */
static const uint8_t (*get_letter(char c))[3] {
    if (c >= 'a' && c <= 'z') return FONT_LETTERS[c - 'a'];
    if (c >= 'A' && c <= 'Z') return FONT_LETTERS[c - 'A'];
    if (c == ' ')              return FONT_LETTERS[26];
    return nullptr;
}
